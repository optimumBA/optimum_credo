defmodule OptimumCredo.Check.Readability.DescribeFunctionArity do
  @moduledoc """
  Finds `describe` names in unit tests that are not `function/arity`.

  Path scoping: files whose path contains one of `web_paths` (default `_web/`) may use
  the route form (`"/register"`, optionally with an HTTP verb: `"GET /register"`) instead; `ignore_paths` (support, feature and integration
  tests) are skipped. If `unit_paths` is non-empty only matching non-web files are checked.
  A `function/arity` name may be followed by a qualifier (`"parse/2 with blanks"`), and the
  `describe "on_mount :hook"` form generated by `phx.gen.auth` is accepted by default.
  Only literal string names are inspected. Patterns are regex sources or `Regex` values.
  """

  use Credo.Check,
    base_priority: :low,
    category: :readability,
    param_defaults: [
      describe_pattern: "^\\w+[?!]?/\\d+( [^\\n]+)?$",
      web_describe_pattern: "^([A-Z]+ )?/",
      web_paths: ["_web/"],
      unit_paths: [],
      ignore_paths: ["test/support/", "/features/", "/integration/"],
      allowed_patterns: ["^on_mount :\\w+$"]
    ],
    explanations: [
      check: """
      Name unit-test `describe` blocks after the function and arity, and web tests after
      the route.

      Bad:   describe "registering a user" do
      Good:  describe "register_user/1" do
      Good (web tests): describe "/register" do

      Use `allowed_patterns` for deliberate groupings such as `"^when "`.
      """,
      params: [
        describe_pattern: "Regex source a unit-test describe name must match.",
        web_describe_pattern: "Additional regex source accepted in web-test paths.",
        web_paths: "Path fragments identifying web tests.",
        unit_paths: "If non-empty, restrict the check to files matching these fragments.",
        ignore_paths: "Path fragments to skip.",
        allowed_patterns: "Regex sources of describe names that are always accepted."
      ]
    ]

  alias OptimumCredo.TestsSupport

  @doc false
  @spec run(Credo.SourceFile.t(), keyword()) :: [Credo.Issue.t()]
  def run(%Credo.SourceFile{} = source_file, params) do
    web? = TestsSupport.path_matches?(source_file, Params.get(params, :web_paths, __MODULE__))

    if checked?(source_file, params, web?) do
      issue_meta = IssueMeta.for(source_file, params)
      accepted = accepted_patterns(params, web?)

      source_file
      |> TestsSupport.ast()
      |> TestsSupport.blocks([:describe])
      |> Enum.filter(&(is_binary(&1.name) and not TestsSupport.pattern_match?(accepted, &1.name)))
      |> Enum.map(&describe_issue(&1, web?, issue_meta))
    else
      []
    end
  end

  defp checked?(source_file, params, web?) do
    ignore = Params.get(params, :ignore_paths, __MODULE__)
    unit_paths = Params.get(params, :unit_paths, __MODULE__)
    scoped? = web? or unit_paths == [] or TestsSupport.path_matches?(source_file, unit_paths)

    TestsSupport.test_file?(source_file) and
      not TestsSupport.path_matches?(source_file, ignore) and scoped?
  end

  defp accepted_patterns(params, web?) do
    web_patterns = if web?, do: [Params.get(params, :web_describe_pattern, __MODULE__)], else: []

    [Params.get(params, :describe_pattern, __MODULE__)] ++
      web_patterns ++ Params.get(params, :allowed_patterns, __MODULE__)
  end

  defp describe_issue(describe, web?, issue_meta) do
    expected = if web?, do: "function/arity or a route like \"/path\"", else: "function/arity"

    format_issue(issue_meta,
      message: "describe #{inspect(describe.name)} should be named #{expected}.",
      line_no: describe.line
    )
  end
end
