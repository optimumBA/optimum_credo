defmodule OptimumCredo.Check.Readability.LlmScaffoldingComment do
  @moduledoc """
  Finds comments that read like leftover AI-assistant scaffolding.

  Typographic apostrophes (`Here\u2019s`) are normalised first. Only real comments (never
  strings or docs) are matched against case-insensitive `patterns` plus `extra_patterns`:
  conversational openers ("Here's the updated ..."), "I've added ...", "rest of the code
  remains the same", "generated by <assistant>" and "implementation goes here".

  `Step N:` comments are deliberately not matched, because people write them too; add
  `"^step \\d+\\s*:"` to `extra_patterns` to catch them. This is lexical guesswork: it will
  miss scaffolding in other phrasing and can flag a human who writes like an assistant.
  """

  use Credo.Check,
    base_priority: :low,
    category: :readability,
    param_defaults: [
      patterns: [
        "^(here'?s|here is|here are) (the |an? |your )?(updated|revised|fixed|complete|final|new|modified|refactored|corrected|improved|implementation|code|solution|function)\\b",
        "^(certainly|sure|of course|absolutely)[!,.]",
        "\\bas an ai\\b",
        "^(i'?ve|i have) (added|updated|created|fixed|implemented|removed|refactored)\\b",
        "^let me\\b",
        "\\b(rest|remainder) of (the )?(code|file|function|module|implementation)\\b.*\\b(remains?|unchanged|same|here)\\b",
        "^\\.{3}\\s*(existing|rest of|previous|other)\\b",
        "\\b(generated|written|created|authored) (by|with) (claude|chatgpt|gpt|copilot|cursor|an? ai|ai)\\b",
        "\\b(implementation|code|logic) (goes|should go|belongs) here\\b",
        "\\byour (code|implementation|logic) here\\b"
      ],
      extra_patterns: []
    ],
    explanations: [
      check: """
      Remove assistant chatter and scaffolding before review; comments should explain why.

      Bad:   # Here's the updated function with error handling
      Good:  # Retries once because the upstream API drops idle connections
      """,
      params: [
        patterns: "Case-insensitive regex sources matched against comment text.",
        extra_patterns: "Additional regex sources, appended to `patterns`."
      ]
    ]

  alias OptimumCredo.TestsSupport

  @doc false
  @spec run(Credo.SourceFile.t(), keyword()) :: [Credo.Issue.t()]
  def run(%Credo.SourceFile{} = source_file, params) do
    issue_meta = IssueMeta.for(source_file, params)

    patterns =
      Enum.map(
        Params.get(params, :patterns, __MODULE__) ++
          Params.get(params, :extra_patterns, __MODULE__),
        fn
          %Regex{} = regex -> regex
          source -> Regex.compile!(source, "iu")
        end
      )

    source_file
    |> TestsSupport.comments()
    |> Enum.filter(fn c ->
      text = String.replace(c.text, ["\u2018", "\u2019"], "'")
      Enum.any?(patterns, &Regex.match?(&1, text))
    end)
    |> Enum.map(fn c ->
      format_issue(issue_meta,
        message: "Comment looks like AI scaffolding; remove it or explain why instead.",
        line_no: c.line
      )
    end)
  end
end
