defmodule OptimumCredo.Check.Readability.FunctionOrder do
  @moduledoc """
  Opt-in check for the order of function definitions inside a module.

  `function_order` selects the convention and defaults to `:off`, so enabling the check
  without choosing a convention does nothing (alphabetical and call-site ordering
  can conflict, so the project must choose one):

  - `:alphabetical`: within each visibility group (`def`/`defmacro`/`defdelegate` and
    `defp`/`defmacrop`), function names appear in alphabetical order. The first
    out-of-order function is reported once per group.
  - `:callers_first`: a private function is defined below the first function that
    calls it.
  - `:off` (default): the check does nothing.

  Any other `function_order` value raises `ArgumentError` instead of silently picking a
  convention.

  Clauses of one function (consecutive clauses with the same name and arity) form one
  unit. Functions annotated with `@impl` are never reported (callback order usually
  follows the behaviour); the `@impl` applies to the annotated name and arity only, so a
  same-named helper of another arity is still checked. In `:callers_first`, `@impl`
  callbacks still count as callers of the private functions they call.

  This is a static heuristic. Callers are literal local calls (a piped value counts as an
  argument) and `&name/arity` captures, matched by name and arity, with default arguments
  covering the lower arities. Calls inside `quote`, through `apply/3`, or generated by
  macros are invisible.

  ## Parameters

  - `function_order`: `:off` (default), `:alphabetical`, or `:callers_first`.
  - `min_run`: minimum number of functions in a visibility group for `:alphabetical`
    (default `3`).
  """

  use Credo.Check,
    base_priority: :low,
    category: :readability,
    param_defaults: [function_order: :off, min_run: 3],
    explanations: [
      check: """
      Keep function definitions in a predictable order. Choose one convention with
      `function_order`: alphabetical within public and private groups, or private
      functions below their first caller.

      ## Bad (`:alphabetical`)

      ```elixir
      def update(thing), do: thing
      def create(thing), do: thing
      def delete(thing), do: thing
      ```

      ## Good (`:alphabetical`)

      ```elixir
      def create(thing), do: thing
      def delete(thing), do: thing
      def update(thing), do: thing
      ```

      Callbacks marked with `@impl` are ignored. Callers are matched by name and arity.
      The check does nothing until `function_order` is set to `:alphabetical` or
      `:callers_first`.
      """,
      params: [
        function_order: "`:off` (default), `:alphabetical`, or `:callers_first`.",
        min_run: "Minimum functions in a visibility group for `:alphabetical`."
      ]
    ]

  alias OptimumCredo.OptimumStructureSupport

  @private [:defp, :defmacrop]

  @doc false
  @spec run(Credo.SourceFile.t(), keyword()) :: [Credo.Issue.t()]
  def run(%Credo.SourceFile{} = source_file, params) do
    issue_meta = IssueMeta.for(source_file, params)

    order =
      params
      |> Params.get(:function_order, __MODULE__)
      |> normalize!()

    min_run = Params.get(params, :min_run, __MODULE__)

    if order == :off do
      []
    else
      Credo.Code.prewalk(
        source_file,
        fn
          {:defmodule, _meta, [_name, [do: body]]} = ast, issues ->
            units =
              body
              |> OptimumStructureSupport.statements()
              |> OptimumStructureSupport.functions()
              |> units()

            {ast, issues ++ check(order, units, min_run, issue_meta)}

          ast, issues ->
            {ast, issues}
        end
      )
    end
  end

  defp normalize!(order) when order in [:off, :alphabetical, :callers_first], do: order
  defp normalize!("off"), do: :off
  defp normalize!("alphabetical"), do: :alphabetical
  defp normalize!("callers_first"), do: :callers_first

  defp normalize!(order) do
    raise ArgumentError,
          "invalid function_order #{inspect(order)} for #{inspect(__MODULE__)}; " <>
            "use :off, :alphabetical or :callers_first"
  end

  # Consecutive clauses of one name and arity form a single unit.
  defp units(clauses) do
    clauses
    |> Enum.chunk_by(&{&1.name, &1.arity})
    |> Enum.map(fn [first | _tail] = chunk ->
      %{
        name: first.name,
        arity: first.arity,
        arities: first.arities,
        private?: first.kind in @private,
        line: first.line,
        impl?: Enum.any?(chunk, & &1.impl?),
        calls:
          chunk
          |> Enum.map(& &1.code)
          |> OptimumStructureSupport.local_calls()
      }
    end)
  end

  defp alphabetical_issues(private?, members, min_run, issue_meta) do
    entries = Enum.map(members, &{Atom.to_string(&1.name), &1.line})

    with true <- length(members) >= min_run,
         {previous, current, line} <- OptimumStructureSupport.first_unsorted(entries) do
      [
        format_issue(issue_meta,
          message:
            "Define #{visibility(private?)} function #{current} before #{previous} to keep functions alphabetical.",
          line_no: line
        )
      ]
    else
      _other -> []
    end
  end

  defp visibility(true), do: "private"
  defp visibility(false), do: "public"

  defp check(:alphabetical, units, min_run, issue_meta) do
    units
    |> Enum.reject(& &1.impl?)
    |> Enum.group_by(& &1.private?)
    |> Enum.flat_map(fn {private?, members} ->
      alphabetical_issues(private?, members, min_run, issue_meta)
    end)
    |> Enum.sort_by(& &1.line_no)
  end

  defp check(:callers_first, units, _min_run, issue_meta) do
    indexed = Enum.with_index(units)

    Enum.flat_map(indexed, fn {unit, index} ->
      with true <- unit.private? and not unit.impl?,
           {caller, caller_index} when caller_index > index <- first_caller(unit, indexed) do
        [
          format_issue(issue_meta,
            message:
              "Define private function #{unit.name}/#{unit.arity} below its first caller " <>
                "#{caller.name}/#{caller.arity}.",
            line_no: unit.line
          )
        ]
      else
        _other -> []
      end
    end)
  end

  defp first_caller(unit, indexed) do
    Enum.find(indexed, fn {other, _index} ->
      {other.name, other.arity} != {unit.name, unit.arity} and
        Enum.any?(unit.arities, &MapSet.member?(other.calls, {unit.name, &1}))
    end)
  end
end
