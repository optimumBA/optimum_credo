defmodule OptimumCredo.Check.Readability.LlmScaffoldingCommentTest do
  use Credo.Test.Case, async: true

  alias OptimumCredo.Check.Readability.LlmScaffoldingComment

  defp run(code, params \\ []) do
    code
    |> to_source_file()
    |> run_check(LlmScaffoldingComment, params)
  end

  test "reports typical assistant scaffolding comments" do
    """
    defmodule A do
      # Here's the updated function with error handling
      # Certainly! Adding the check.
      # I've added a guard
      # Let me explain the next part
      # ... existing code ...
      # The rest of the code remains the same
      # Generated by Claude
      # Implementation goes here
      def a, do: 1
    end
    """
    |> run()
    |> assert_issues(fn issues -> assert length(issues) == 8 end)
  end

  test "accepts ordinary why-comments" do
    """
    defmodule A do
      # Retry once because the upstream drops idle connections
      # Here is a gotcha: the cache is warmed lazily
      def a, do: 1 # sure thing
    end
    """
    |> run()
    |> refute_issues()
  end

  test "ignores strings, docs and heredocs" do
    ~S'''
    defmodule A do
      @moduledoc """
      # Here's the updated function
      Certainly! I've added this.
      """
      def a, do: "# Let me explain"
    end
    '''
    |> run()
    |> refute_issues()
  end

  test "extra_patterns and patterns params" do
    code = """
    defmodule A do
      # per the ticket discussion
      def a, do: 1
    end
    """

    code
    |> run()
    |> refute_issues()

    code
    |> run(extra_patterns: ["ticket discussion"])
    |> assert_issue()

    code
    |> run(patterns: [])
    |> refute_issues()
  end

  test "typographic apostrophes are normalised" do
    "defmodule A do\n  # Here\u2019s the updated function\n  # I\u2019ve added error handling\nend\n"
    |> run()
    |> assert_issues(fn issues -> assert length(issues) == 2 end)
  end

  test "inline comments are checked, strings and docs are not" do
    ~S'''
    defmodule A do
      @doc "Here's the updated function"
      def a, do: "# Certainly! sure" # Certainly! here you go
    end
    '''
    |> run()
    |> assert_issue(fn issue -> assert issue.line_no == 3 end)
  end

  test "extra_patterns accept Regex values and strings" do
    code = "defmodule A do\n  # vibe coded\n  # AI wrote this\nend\n"

    code
    |> run()
    |> refute_issues()

    code
    |> run(extra_patterns: [~r/vibe coded/i, "ai wrote"])
    |> assert_issues(fn issues -> assert length(issues) == 2 end)
  end

  test "Step N comments and prose containing 'implementation here' are not scaffolding" do
    code = """
    defmodule A do
      # Step 1: parse input
      # the original implementation here still reads the socket
      # Your code here
      def a, do: 1
    end
    """

    code
    |> run()
    |> assert_issue(fn issue -> assert issue.line_no == 4 end)

    code
    |> run(extra_patterns: ["^step \\d+\\s*:"])
    |> assert_issues(fn issues -> assert Enum.map(issues, & &1.line_no) == [2, 4] end)
  end
end
